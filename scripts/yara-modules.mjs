/**
 * Regenerates src/languages/yara/modules-data.js from libyara's module sources, so completion,
 * hover and lint know exactly what the compiler knows (fields, types, function overloads).
 *
 *   curl -sL https://github.com/VirusTotal/yara/archive/refs/tags/v4.5.4.tar.gz | tar xz
 *   node scripts/yara-modules.mjs yara-4.5.4
 *
 * Docs already in modules-data.js are kept: only the structure comes from the C code.
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const MODULE_NAMES = ['pe', 'elf', 'math', 'hash', 'dotnet', 'time', 'console', 'string', 'macho', 'dex', 'magic', 'cuckoo'];
// Not compiled into every build (yara-python wheels leave them out): the lint says so.
const OPTIONAL = new Set(['macho', 'dex', 'magic', 'cuckoo']);
const ARG = { i: 'integer', s: 'string', f: 'float', r: 'regex', b: 'boolean' };
const OUT = new URL('../src/languages/yara/modules-data.js', import.meta.url);

const src = process.argv[2];
if (!src || !existsSync(join(src, 'libyara/modules'))) {
    console.error('usage: node scripts/yara-modules.mjs <yara source dir>');
    process.exit(1);
}
const old = existsSync(OUT) ? (await import(OUT.href)).MODULE_DATA : {};

function parseModule(name) {
    const dir = join(src, 'libyara/modules', name);
    const file = readdirSync(dir).find(f => f === `${name}.c`);
    const code = readFileSync(join(dir, file), 'utf8');
    const body = code.slice(code.indexOf('begin_declarations'), code.indexOf('end_declarations'));
    const root = { kind: 'module', fields: {} };
    const stack = [root];
    const re = /(declare_\w+|begin_\w+|end_\w+)\s*\(([^;]*?)\)\s*;?/g;
    for (const m of body.matchAll(re)) {
        const [, what, rawArgs] = m;
        const args = [...rawArgs.matchAll(/"([^"]*)"/g)].map(x => x[1]);
        const top = stack[stack.length - 1];
        const put = (key, node) => { top.fields[key] = top.fields[key] || node; return top.fields[key]; };
        switch (what) {
            case 'declare_integer': put(args[0], /^[A-Z0-9_]+$/.test(args[0]) ? { kind: 'constant', type: 'integer' } : { kind: 'value', type: 'integer' }); break;
            case 'declare_float': put(args[0], { kind: 'value', type: 'float' }); break;
            case 'declare_string': put(args[0], { kind: 'value', type: 'string' }); break;
            case 'declare_integer_array': put(args[0], { kind: 'array', type: 'integer' }); break;
            case 'declare_string_array': put(args[0], { kind: 'array', type: 'string' }); break;
            case 'declare_float_array': put(args[0], { kind: 'array', type: 'float' }); break;
            case 'declare_integer_dictionary': put(args[0], { kind: 'dict', type: 'integer' }); break;
            case 'declare_string_dictionary': put(args[0], { kind: 'dict', type: 'string' }); break;
            case 'declare_float_dictionary': put(args[0], { kind: 'dict', type: 'float' }); break;
            case 'declare_function': {
                const fn = put(args[0], { kind: 'function', overloads: [] });
                const sig = { args: [...args[1]].map(c => ARG[c] || c), ret: ARG[args[2]] || args[2] };
                if (!fn.overloads.some(o => o.args.join() === sig.args.join())) fn.overloads.push(sig);
                break;
            }
            case 'begin_struct': stack.push(put(args[0], { kind: 'struct', fields: {} })); break;
            case 'begin_struct_array': stack.push(put(args[0], { kind: 'array', fields: {} })); break;
            case 'begin_struct_dictionary': stack.push(put(args[0], { kind: 'dict', fields: {} })); break;
            case 'end_struct': case 'end_struct_array': case 'end_struct_dictionary': stack.pop(); break;
        }
    }
    return root;
}

/** Keep hand-written docs and signatures from the previous file. */
function mergeDocs(node, prev) {
    if (prev && prev.doc) node.doc = prev.doc;
    if (prev && prev.sig && node.kind === 'function') node.sig = prev.sig;
    if (node.fields) for (const [k, child] of Object.entries(node.fields)) mergeDocs(child, prev && prev.fields && prev.fields[k]);
    return node;
}

const data = {};
for (const name of MODULE_NAMES) {
    const mod = mergeDocs(parseModule(name), old[name]);
    data[name] = { doc: (old[name] && old[name].doc) || '', optional: OPTIONAL.has(name) || undefined, fields: mod.fields };
}

const header = `/**
 * GENERATED by scripts/yara-modules.mjs from libyara ${src.replace(/.*yara-/, '')}: structure of every
 * module (fields, types, function overloads). Edit the docs here; regenerate for the structure.
 */
`;
writeFileSync(OUT, `${header}export const MODULE_DATA = ${JSON.stringify(data)};\n`);
const count = (n) => Object.values(n.fields || {}).reduce((a, c) => a + 1 + count(c), 0);
console.log(Object.entries(data).map(([k, v]) => `${k}: ${count(v)}`).join(', '));
